


CREATE PROCEDURE [dbo].[USP_CLONA_PECA] @IdPeca int = 0
	
AS
BEGIN
	
	SET NOCOUNT ON;

DECLARE @NovoID INT

INSERT INTO [1TabPeças]
           ([IDCliente]
           ,[Num]
           ,[Classe]
--           ,[Modêlo]
           ,[Descrição]
           ,[Oficial]
           ,[Família]
           ,[Quant]
           ,[Origem]
           ,[DataIn]
           ,[Custo]
           ,[Dólar]
           ,[Posição]
           ,[Vendida]
           ,[DataVenda]
           ,[Tipo]
           ,[Vendedora]
           ,[Valor]
           ,[Comissão]
           ,[Com2]
           ,[Real]
           ,[DólarVenda]
           ,[Cheque]
           ,[Pré]
           ,[PosiçãoPré]
           ,[Cartão]
           ,[ContaCorrente]
           ,[Desconto]
           ,[A Receber]
           ,[Pré-2]
           ,[PosPré2]
           ,[Pré-3]
           ,[PosPré3]
           ,[Conserto]
           ,[PC]
           ,[PCQtde]
           ,[Espécie]
           ,[MOExt]
           ,[MOInt]
           ,[Custo2]
           ,[Oficina]
           ,[DataReg]
           ,[Desenho]
           ,[Madeira]
           ,[Couro]
           ,[Cravação]
           ,[Outras]
           ,[Obs]
           ,[DataFabric]
           ,[PrVenda]
           ,[CustoAnt]
           ,[PrVendaAnt]
           ,[Excluir]
           ,[Volta]
           ,[IdPeçaOrigem]
           ,[Saida]
           ,[Foto]
           ,[SizeMode])
     Select [IDCliente]
           ,[Num]
           ,[Classe]
--           ,[Modêlo]
           ,[Descrição]
           ,[Oficial]
           ,[Família]
           ,[Quant]
           ,[Origem]
           ,[DataIn]
           ,[Custo]
           ,[Dólar]
           ,[Posição]
           ,0
           ,''
           ,[Tipo]
           ,[Vendedora]
           ,[Valor]
           ,[Comissão]
           ,[Com2]
           ,[Real]
           ,[DólarVenda]
           ,[Cheque]
           ,[Pré]
           ,[PosiçãoPré]
           ,[Cartão]
           ,[ContaCorrente]
           ,[Desconto]
           ,[A Receber]
           ,[Pré-2]
           ,[PosPré2]
           ,[Pré-3]
           ,[PosPré3]
           ,[Conserto]
           ,[PC]
           ,[PCQtde]
           ,[Espécie]
           ,[MOExt]
           ,[MOInt]
           ,[Custo2]
           ,[Oficina]
           ,GETDATE()
           ,[Desenho]
           ,[Madeira]
           ,[Couro]
           ,[Cravação]
           ,[Outras]
           ,[Obs]
           ,[DataFabric]
           ,[PrVenda]
           ,[CustoAnt]
           ,[PrVendaAnt]
           ,[Excluir]
           ,[Volta]
           ,[IdPeçaOrigem]
           ,[Saida]
           ,[Foto]
           ,[SizeMode]
	From [1TabPeças]
	WHERE IDPeça = @IdPeca;

SET @NovoID = SCOPE_IDENTITY();

INSERT INTO [dbo].[METAIS]
           ([Id]
           ,[OuroQtde]
           ,[PaladiumQtde]
           ,[PrataQtde]
           ,[PlatinaQtde]
           ,[PerdaPerc]
           ,[PerdaQtde]
           ,[SistemaQtde]
           ,[TotalQtde]
           ,[TotalValor]
           ,[SistemaValor]
           ,[OuroV]
           ,[PaladiumV]
           ,[PrataV]
           ,[PlatinaV])
     Select
           @NovoID
           ,[OuroQtde]
           ,[PaladiumQtde]
           ,[PrataQtde]
           ,[PlatinaQtde]
           ,[PerdaPerc]
           ,[PerdaQtde]
           ,[SistemaQtde]
           ,[TotalQtde]
           ,[TotalValor]
           ,[SistemaValor]
           ,[OuroV]
           ,[PaladiumV]
           ,[PrataV]
           ,[PlatinaV]
	From METAIS
	WHERE Id = @IdPeca;

INSERT INTO [PEDRAS]
           ([Id]
           ,[DiamantesQtde]
           ,[DiamantesValor]
           ,[RubiQtde]
           ,[RubiValor]
           ,[SafiraQtde]
           ,[SafiraValor]
           ,[EsmeraldaQtde]
           ,[EsmeraldaValor]
           ,[CitrinoQtde]
           ,[CitrinoValor]
           ,[PedrasBrasQtde]
           ,[PedrasBrasValor]
           ,[PerolasQtde]
           ,[PerolasValor]
           ,[DiamantesCT]
           ,[RubisCT]
           ,[SafirasCT]
           ,[EsmeraldasCT]
           ,[PedrasCT]
           ,[BrasCT]
           ,[PerolasCT]
           ,[Diamantes2Qtde]
           ,[Diamantes2Valor]
           ,[Diamantes2CT])
     Select
           @NovoID
           ,[DiamantesQtde]
           ,[DiamantesValor]
           ,[RubiQtde]
           ,[RubiValor]
           ,[SafiraQtde]
           ,[SafiraValor]
           ,[EsmeraldaQtde]
           ,[EsmeraldaValor]
           ,[CitrinoQtde]
           ,[CitrinoValor]
           ,[PedrasBrasQtde]
           ,[PedrasBrasValor]
           ,[PerolasQtde]
           ,[PerolasValor]
           ,[DiamantesCT]
           ,[RubisCT]
           ,[SafirasCT]
           ,[EsmeraldasCT]
           ,[PedrasCT]
           ,[BrasCT]
           ,[PerolasCT]
           ,[Diamantes2Qtde]
           ,[Diamantes2Valor]
           ,[Diamantes2CT]
	from PEDRAS
	where Id=@IdPeca;


END
